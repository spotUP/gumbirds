#!/usr/bin/env python3
"""assets/attract/attract_icons.json + approved overlay layout -> C header (stdout, or --out PATH).
Usage: python3.14 -I tools/build_attract_icons.py [--out build/gen/attract_icons.h] [--fix-base 0x400]
Header: tile count, fix palette words, per-frame tile tables (fix code = ATTRACT_ICON_FIX_BASE + tile id, ATTRACT_ICON_BLANK = skip),
and the corner-layout cells taken from v_corner in the overlay draft (the layout stays defined there, read via ast, not copied).
Reuses tools/sprite_pipeline.rgb_to_ng for the colour words."""
import argparse, ast, json, os, subprocess, sys, tempfile
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sprite_pipeline as sp  # rgb_to_ng, expand5
import numpy as np
from PIL import Image

TILETOOL = os.environ.get("TILETOOL", "/opt/homebrew/bin/tiletool.py")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OVERLAY = os.path.join(ROOT, "thoughts/spot/drafts/2026-11-13-attract-overlay/draw_overlay.py")
NAMES = ("CAPTIONS", "STATES", "v_corner")


def layout():
    """Execute only CAPTIONS, STATES and v_corner of the draft (it draws images on import otherwise)."""
    tree = ast.parse(open(OVERLAY).read())
    keep = [n for n in tree.body if (isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") in NAMES)
            or (isinstance(n, ast.FunctionDef) and n.name in NAMES)]
    assert {getattr(n, "name", None) or n.targets[0].id for n in keep} == set(NAMES), "layout names not found in draft"
    ns = {}
    exec(compile(ast.Module(keep, []), OVERLAY, "exec"), ns)
    return ns["CAPTIONS"], ns["STATES"], ns["v_corner"]


def pack_fix(atlas_png, n, out):
    """Pack the n icon tiles into S-ROM fix format with tiletool (one 16-tile row per call, like build_tripmeter_tiles.py), decode again and compare."""
    img = Image.open(atlas_png)
    px = np.array(img)
    assert img.mode == "P" and px.shape[1] == 128
    blob = b""
    with tempfile.TemporaryDirectory() as tmp:
        for r in range((n + 15) // 16):
            rowpng, full, dec = (os.path.join(tmp, x) for x in ("r.png", "r.fix", "d.png"))
            row = Image.fromarray(np.ascontiguousarray(px[r * 8:r * 8 + 8]), "P")
            row.putpalette(img.getpalette())
            row.save(rowpng)
            subprocess.run([TILETOOL, "--fix", "-c", rowpng, "-o", full], check=True)
            data = open(full, "rb").read()[:32 * 16]
            subprocess.run([TILETOOL, "--fix", "-x", full, "-o", dec, "-w", "128"], check=True)
            if not (np.array(Image.open(dec))[:8, :] == px[r * 8:r * 8 + 8]).all():
                sp.die("fix round trip differs in row %d" % r)
            blob += data
    open(out, "wb").write(blob[:32 * n])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--meta", default=os.path.join(ROOT, "assets/attract/attract_icons.json"))
    ap.add_argument("--out")
    ap.add_argument("--fix-base", type=lambda s: int(s, 0), default=0x400)
    a = ap.parse_args()
    m = json.load(open(a.meta))
    n, blank = m["tile_count"], m["blank"]
    assert a.fix_base + n - 1 <= 0xFFF and len(m["palette"]) <= 16
    words = [0x8000] + [sp.rgb_to_ng(tuple(sp.expand5(v) for v in p["rgb5"])) for p in m["palette"][1:]]
    words += [0] * (16 - len(words))
    caps, states, v_corner = layout()
    h = ["/* Generated by tools/build_attract_icons.py from assets/attract/attract_icons.json. Do not edit. */",
         "#ifndef ATTRACT_ICONS_H", "#define ATTRACT_ICONS_H", "#include <stdint.h>", "",
         "#define ATTRACT_ICON_TILES %d" % n, "#define ATTRACT_ICON_FIX_BASE 0x%03X /* tile id k is fix code base + k */" % a.fix_base,
         "#define ATTRACT_ICON_BLANK -1 /* cell stays untouched */", "",
         "static const uint16_t attract_icon_palette[16] = {", "    " + ", ".join("0x%04x" % w for w in words), "};", ""]
    fnames = list(m["frames"])
    for i, f in enumerate(fnames):
        h.append("#define ATTRACT_FRAME_%s %d" % (f.upper(), i))
    h += ["#define ATTRACT_FRAME_COUNT %d" % len(fnames), "",
          "typedef struct { uint8_t cols, rows; const int8_t *tiles; } attract_frame_t; /* row-major cols * rows */"]
    for f in fnames:
        g = m["frames"][f]
        assert all(len(r) == g["cols"] for r in g["tiles"]) and len(g["tiles"]) == g["rows"]
        h.append("static const int8_t attract_tiles_%s[%d] = { %s };" % (f, g["cols"] * g["rows"],
                 ", ".join(str(v) for r in g["tiles"] for v in r)))
    h += ["static const attract_frame_t attract_frames[ATTRACT_FRAME_COUNT] = {"]
    h += ["    { %d, %d, attract_tiles_%s }," % (m["frames"][f]["cols"], m["frames"][f]["rows"], f) for f in fnames] + ["};", ""]
    # corner layout: item positions are identical for every state/caption; read them from one call and assert that
    pos = None
    for s in states:
        for c in caps.values():
            items = v_corner(s, c)
            icons = [(i[1], i[2], i[3]) for i in items if i[0] == "icon"]
            p = ([(i[2], i[3]) for i in items if i[0] == "text"], [(i[1], i[2]) for i in icons])
            assert pos is None or pos == p, "layout depends on state or caption"
            pos = p
    (t1, t2, tact), (lever, a_, start) = pos[0], pos[1]
    h += ["/* Overlay cells (fix column, row) from v_corner: caption line 1, line 2, action word, then the three icon top-left cells. */"]
    for k, (col, row) in zip(("CAP1", "CAP2", "ACTION", "LEVER", "BUTTON", "START"), pos[0][:3] + pos[1]):
        h.append("#define ATTRACT_%s_COL %d\n#define ATTRACT_%s_ROW %d" % (k, col, k, row))
    h += ["", "/* Captions per mode: two lines. Palette: white; the action word is gold. */"]
    h.append("static const char *const attract_captions[%d][2] = {" % len(caps))
    for mode, c in caps.items():
        h.append('    { "%s", "%s" }, /* %s */' % (*c.split("|"), mode))
    h += ["};", "", "/* States: lever, A and Start frame, active word. */",
          "static const struct { uint8_t lever, a, start; const char *word; } attract_states[%d] = {" % len(states)]
    for s, (lv, ab, st, w) in states.items():
        h.append('    { ATTRACT_FRAME_%s, ATTRACT_FRAME_%s, ATTRACT_FRAME_%s, "%s" }, /* %s */' % (lv.upper(), ab.upper(), st.upper(), w, s))
    h += ["};", "", "#endif", ""]
    text = "\n".join(h)
    if a.out:
        open(a.out, "w").write(text)
        pack_fix(os.path.join(ROOT, "assets/attract", m["atlas"]), n, os.path.splitext(a.out)[0] + ".fix")
        print("[OK] %s: %d tiles, %d frames, %d states, %d modes" % (a.out, n, len(fnames), len(states), len(caps)))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
