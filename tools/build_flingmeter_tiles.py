#!/usr/bin/env python3
"""Gum Fling / Big Blow / Burst Race meter fix tiles: hand-pixeled grids in tools/flingmeter_art.py (owner pick C, draft
thoughts/shared/drafts/2026-11-20-fling-meter) -> build/gen/flingmeter_tiles.h (palette words, tile tables) + flingmeter_tiles.fix
(S-ROM order: font, attract icons, result scene, rulecard, these). Usage: python3.14 -I tools/build_flingmeter_tiles.py --out build/gen/flingmeter_tiles.h
Code here only cuts the grids into unique 8x8 tiles (blank tiles map to 0xFF = FIXFONT_BLANK) and packs them with tools/build_attract_icons.pack_fix."""
import argparse, os, sys, tempfile
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from PIL import Image
import sprite_pipeline as sp
import build_attract_icons as icons
import flingmeter_art as A

BLANK = 0xFF
CELLS = ["GUM_A", "GUM_B", "FRONT8", "FRONT4", "EMPTY", "EMPTY_TICK", "EMPTY_MAJOR", "CAP_L", "CAP_R"]
DEGS = sorted(A.N)
KEYS = list(A.PINK)   # palette entry k+1 = letter KEYS[k]


class Atlas:
    def __init__(self): self.tiles, self.index = [], {}
    def add(self, rows):
        if all(c == "." for r in rows for c in r): return BLANK
        key = tuple(rows)
        if key not in self.index: self.index[key] = len(self.tiles); self.tiles.append(key)
        return self.index[key]
    def cut(self, rows, w):   # a w x h char grid -> row-major tile ids
        return [self.add([r[x:x + 8] for r in rows[y:y + 8]]) for y in range(0, len(rows), 8) for x in range(0, w, 8)]


def dial(deg):
    """24 x 24 dial with the needle of angle deg: pivot at (2, 21), 2 px needle, hub; same placement as the draft."""
    cv = [list(r) for r in A.DIAL]
    px, steep = A.N[deg], deg > 45
    for dx, dy in px:
        sx, sy = (dx + 1, dy) if steep else (dx, dy + 1)
        cv[21 - sy][2 + sx] = "V"
    for i, (dx, dy) in enumerate(px): cv[21 - dy][2 + dx] = "y" if i >= len(px) - 3 else "W"
    for (dx, dy), c in A.HUB.items(): cv[21 - dy][2 + dx] = c
    return ["".join(r) for r in cv]


def label(word):
    cv = [["."] * 32 for _ in range(16)]
    A.label(cv, 0, 0, word)
    return ["".join(r) for r in cv]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    at = Atlas()
    cells = [[at.add(g[:8]), at.add(g[8:])] for g in (getattr(A, n) for n in CELLS)]
    dials = [at.cut(dial(d), 24) for d in DEGS]
    lab = {w: at.cut(label(w), 32) for w in ("ANGLE", "POWER")}
    n = len(at.tiles)
    assert n <= 0xFE, n
    px = np.zeros((((n + 15) // 16) * 8, 128), np.uint8)
    for i, t in enumerate(at.tiles):
        for y, r in enumerate(t):
            for x, c in enumerate(r): px[(i // 16) * 8 + y, (i % 16) * 8 + x] = 0 if c == "." else KEYS.index(c) + 1
    img = Image.fromarray(px, "P")
    rgb = lambda h: [sp.expand5(sp.to5(int(h[j:j + 2], 16))) for j in (1, 3, 5)]   # draft colours snap to the nearest 5-bit value
    img.putpalette(rgb(A.PINK[KEYS[0]]) + sum((rgb(A.PINK[k]) for k in KEYS), []))   # entry 0 is transparent, never drawn
    fix = os.path.splitext(a.out)[0] + ".fix"
    with tempfile.TemporaryDirectory() as tmp:
        png = os.path.join(tmp, "flingmeter.png")
        img.save(png)
        icons.pack_fix(png, n, fix)

    def words(p): return [0x8000] + [sp.rgb_to_ng(tuple(rgb(p[k]))) for k in KEYS]
    def arr(name, t, per): return "static const uint8_t %s[] = {\n%s\n};" % (name, ",\n".join("    " + ", ".join("0x%02x" % v for v in t[i:i + per]) for i in range(0, len(t), per)))
    mask = sum(1 << c for c, k in enumerate(A.GUM_ORDER) if k == "B")
    open(a.out, "w").write("\n".join([
        "/* Generated by tools/build_flingmeter_tiles.py from tools/flingmeter_art.py. Do not edit. */",
        "#ifndef FLINGMETER_TILES_H", "#define FLINGMETER_TILES_H", "#include <stdint.h>", '#include "gen/rulecard_tiles.h"', "",
        "#define FLINGMETER_FIX_TILES %d" % n,
        "#define FLINGMETER_FIX_BASE (RULECARD_FIX_BASE + RULECARD_FIX_TILES) /* S-ROM order: font, attract icons, result scene, rulecard, these */",
        "#define FLINGMETER_BLANK 0x%02X /* table entry for a blank cell */" % BLANK,
        "#define FLINGMETER_DIAL_COUNT %d" % len(DEGS),
        "#define FLINGMETER_GUM_B_MASK 0x%04x /* bit c set: gum cell c is the B tile */" % mask,
        *["#define FLINGMETER_%s %d /* flingmeter_cell row: top tile, bottom tile */" % (c, i) for i, c in enumerate(CELLS)],
        '_Static_assert(FLINGMETER_FIX_BASE + FLINGMETER_FIX_TILES <= 0x1000, "meter tiles leave the 12-bit fix code range");',
        "/* Palette words: pink tube set and the full power hot swap (same tile art). Entry 0 is unused by fix tiles. */",
        "static const uint16_t flingmeter_palette[16] = { %s };" % ", ".join("0x%04x" % w for w in words(A.PINK)),
        "static const uint16_t flingmeter_hot_palette[16] = { %s };" % ", ".join("0x%04x" % w for w in words(A.HOT)),
        arr("flingmeter_cell", sum(cells, []), 2),
        "static const uint8_t flingmeter_dial_deg[FLINGMETER_DIAL_COUNT] = { %s };" % ", ".join(map(str, DEGS)),
        arr("flingmeter_dial", sum(dials, []), 9) + " /* [degree index][3 x 3 tiles, row-major] */",
        arr("flingmeter_label_angle", lab["ANGLE"], 4) + " /* 4 x 2 tiles */",
        arr("flingmeter_label_power", lab["POWER"], 4) + " /* 4 x 2 tiles */",
        "", "#endif", ""]))
    print("[OK] %s: %d tiles" % (a.out, n))


if __name__ == "__main__":
    main()
