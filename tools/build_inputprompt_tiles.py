#!/usr/bin/env python3
"""Input prompt fix tiles (button caps A B C in up / down / lit states, stick neutral / left / right): hand-pixeled grids in
tools/inputprompt_art.py (owner pick A, draft thoughts/shared/drafts/2026-11-20-input-prompts) -> build/gen/inputprompt_tiles.h (palette
words, tile tables) + inputprompt_tiles.fix (S-ROM order: font, attract icons, result scene, rulecard, flingmeter, these).
Usage: python3.14 -I tools/build_inputprompt_tiles.py --out build/gen/inputprompt_tiles.h
Code here only cuts the grids into unique 8x8 tiles (blank tiles map to 0xFF = blank cell) and packs them with build_attract_icons.pack_fix."""
import argparse, os, sys, tempfile
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from PIL import Image
import sprite_pipeline as sp
import build_attract_icons as icons
import inputprompt_art as A

BLANK = 0xFF
LETTERS, STATES = "ABC", ("up", "down", "glow")


def cap(letter, state):
    g = [list(r) for r in {"up": A.BTN_UP, "down": A.BTN_DOWN, "glow": A.BTN_GLOW}[state]]
    oy = 4 if state == "down" else 2
    for y, row in enumerate(A.LETTER[letter]):
        for x, c in enumerate(row):
            if c != ".": g[oy + y][5 + x] = c
    ramp = A.RAMP[letter] or {}
    return ["".join(ramp.get(c, c) for c in r) for r in g]


class Atlas:
    def __init__(self): self.tiles, self.index = [], {}
    def add(self, rows):
        if all(c == "." for r in rows for c in r): return BLANK
        key = tuple(rows)
        if key not in self.index: self.index[key] = len(self.tiles); self.tiles.append(key)
        return self.index[key]
    def cut(self, rows):   # 16 x 16 grid -> 4 tile ids, row-major
        return [self.add([r[x:x + 8] for r in rows[y:y + 8]]) for y in (0, 8) for x in (0, 8)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    at = Atlas()
    caps = [at.cut(cap(l, s)) for l in LETTERS for s in STATES]
    sticks = [at.cut(g) for g in (A.STICK_N, A.STICK_L, A.STICK_R)]
    n = len(at.tiles)
    assert n <= 0xFE, n
    px = np.zeros((((n + 15) // 16) * 8, 128), np.uint8)
    for i, t in enumerate(at.tiles):
        for y, r in enumerate(t):
            for x, c in enumerate(r): px[(i // 16) * 8 + y, (i % 16) * 8 + x] = 0 if c == "." else A.KEYS.index(c) + 1
    img = Image.fromarray(px, "P")
    img.putpalette([0, 0, 0] + [v for k in A.KEYS for v in A.PAL[k]])
    fix = os.path.splitext(a.out)[0] + ".fix"
    with tempfile.TemporaryDirectory() as tmp:
        png = os.path.join(tmp, "inputprompt.png")
        img.save(png)
        icons.pack_fix(png, n, fix)
    words = [0x8000] + [sp.rgb_to_ng(tuple(A.PAL[k])) for k in A.KEYS]
    def arr(name, t, per): return "static const uint8_t %s[] = {\n%s\n};" % (name, ",\n".join("    " + ", ".join("0x%02x" % v for v in t[i:i + per]) for i in range(0, len(t), per)))
    open(a.out, "w").write("\n".join([
        "/* Generated by tools/build_inputprompt_tiles.py from tools/inputprompt_art.py. Do not edit. */",
        "#ifndef INPUTPROMPT_TILES_H", "#define INPUTPROMPT_TILES_H", "#include <stdint.h>", '#include "gen/flingmeter_tiles.h"', "",
        "#define INPUTPROMPT_FIX_TILES %d" % n,
        "#define INPUTPROMPT_FIX_BASE (FLINGMETER_FIX_BASE + FLINGMETER_FIX_TILES) /* S-ROM order: font, attract icons, result scene, rulecard, flingmeter, these */",
        "#define INPUTPROMPT_BLANK 0x%02X /* table entry for a blank cell */" % BLANK,
        '_Static_assert(INPUTPROMPT_FIX_BASE + INPUTPROMPT_FIX_TILES <= 0x1000, "prompt tiles leave the 12-bit fix code range");',
        "/* Palette words (rules card colours; entry 0 unused by fix tiles). Caps: letter A B C x state up, down, lit. */",
        "static const uint16_t inputprompt_palette[16] = { %s };" % ", ".join("0x%04x" % w for w in words),
        arr("inputprompt_cap", sum(caps, []), 4) + " /* [letter * 3 + state][2 x 2 tiles, row-major] */",
        arr("inputprompt_stick", sum(sticks, []), 4) + " /* [neutral, left, right][2 x 2 tiles] */",
        "", "#endif", ""]))
    print("[OK] %s: %d tiles" % (a.out, n))


if __name__ == "__main__":
    main()
