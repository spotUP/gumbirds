#!/usr/bin/env python3
"""Storm rain fix tiles and tables: assets/rain/rain_data.json (the owner-approved draft v3, exported by tools/export_rain_draft.py;
every grid is hand-typed there) -> build/gen/rain_tiles.h (palette words, cut table, spawn tables) + rain_tiles.fix (S-ROM order: font,
attract icons, result scene, rulecard, flingmeter, input prompts, these). Code here only packs the typed grids; nothing is drawn.
Usage: python3.14 -I tools/build_rain_tiles.py --out build/gen/rain_tiles.h"""
import argparse, json, os, sys, tempfile
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from PIL import Image
import sprite_pipeline as sp
import build_attract_icons as icons

ap = argparse.ArgumentParser()
ap.add_argument("--out", required=True)
ap.add_argument("--data", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "rain", "rain_data.json"))
a = ap.parse_args()
d = json.load(open(a.data))
KEYS, tiles = d["key_order"], d["tiles"]
n = len(tiles)
assert n == 60
px = np.zeros((((n + 15) // 16) * 8, 128), np.uint8)
for i, t in enumerate(tiles):
    for y, r in enumerate(t):
        for x, c in enumerate(r):
            px[(i // 16) * 8 + y, (i % 16) * 8 + x] = 0 if c == "." else KEYS.index(c) + 1
rgb = lambda c: [sp.expand5(sp.to5(v)) for v in c]
img = Image.fromarray(px, "P")
img.putpalette(rgb(d["palette"][KEYS[0]]) + sum((rgb(d["palette"][k]) for k in KEYS), []))
fix = os.path.splitext(a.out)[0] + ".fix"
with tempfile.TemporaryDirectory() as tmp:
    png = os.path.join(tmp, "rain.png")
    img.save(png)
    icons.pack_fix(png, n, fix)
words = lambda p: [sp.rgb_to_ng(tuple(rgb(p[k]))) for k in KEYS]
arr = lambda name, t, per: "static const uint8_t %s[] = {\n%s\n};" % (name, ",\n".join("    " + ", ".join(str(v) for v in t[i:i + per]) for i in range(0, len(t), per)))
# cut table [kind][x phase 0..7][y phase 0 or 4 -> 0/1]: count + 3 x (dcol, drow, tile); an unused combination has count 0
cut = [[0, [0] * 9] for _ in range(6 * 8 * 2)]
for kind, xp, yp, cells in d["cuts"]:
    assert yp in (0, 4) and len(cells) <= 3
    cut[(kind * 8 + xp) * 2 + yp // 4] = [len(cells), sum(([c, r, t] for c, r, t in cells), []) + [0] * (9 - 3 * len(cells))]
spawn = []   # per (distance, gust): (frame, col, row0, rows), light then extra drops merged (the heavy take), sorted by frame
GU = ["lull", "steady", "gale"]
for dist in ("far", "near"):
    for g in GU:
        spawn.append(sorted(d["spawn"]["%s %s L" % (dist, g)] + d["spawn"]["%s %s X" % (dist, g)]))
hud = {m: sum(1 << r for r in rows) for m, rows in d["hud_rows"].items()}
kinds = d["kinds"]
out = ["/* Generated by tools/build_rain_tiles.py from assets/rain/rain_data.json. Do not edit. */", "#ifndef RAIN_TILES_H", "#define RAIN_TILES_H",
       "#include <stdint.h>", '#include "gen/inputprompt_tiles.h"', "",
       "#define RAIN_FIX_TILES %d" % n,
       "#define RAIN_FIX_BASE (INPUTPROMPT_FIX_BASE + INPUTPROMPT_FIX_TILES) /* S-ROM order: font, attract icons, result scene, rulecard, flingmeter, input prompts, these */",
       '_Static_assert(RAIN_FIX_BASE + RAIN_FIX_TILES <= 0x1000, "rain tiles leave the 12-bit fix code range");',
       "#define RAIN_LOOP %d /* frames of the gust timeline */" % d["loop"], "#define RAIN_TAB %d /* far spawn table period */" % d["tab"],
       "#define RAIN_NEAR_TAB %d /* a near table entry fires every this many frames (its frame number doubled) */" % d["near_tab"],
       "#define RAIN_FLASH0 %d /* the draft's first flash frame, kept for the tests */" % d["flash0"],
       "/* Kinds: 0..2 far lull, steady, gale; 3..5 near lull, steady, gale. Kind = 3 * near + gust. */",
       "static const int8_t rain_move[6][3] = { %s }; /* px left, px down per frame, x offset in the spawn cell */" % ", ".join("{%d, %d, %d}" % tuple(m) for m in d["move"]),
       "static const uint8_t rain_height[6] = { %s }; /* streak height in lines */" % ", ".join(map(str, d["streak_height"])),
       "static const uint16_t rain_gust_start[%d] = { %s }; /* gust of entry i: rain_gust_kind[i] (0 lull, 1 steady, 2 gale) */" % (len(d["gusts"]), ", ".join(str(g[0]) for g in d["gusts"])),
       "static const uint8_t rain_gust_kind[%d] = { %s };" % (len(d["gusts"]), ", ".join(str(GU.index(g[1])) for g in d["gusts"])),
       "#define RAIN_GUSTS %d" % len(d["gusts"]),
       "static const uint32_t rain_hud_rows[3] = { 0x%08x, 0x%08x, 0x%08x }; /* screen row bits (fix row = screen row + 2) the rain never enters: arena/arcade, trip, stadium */" % (hud["arena"], hud["trip"], hud["stadium"]),
       "/* Pale storm blue burst: entries 1..5 = H B T F e. */",
       "static const uint16_t rain_palette[5] = { %s };" % ", ".join("0x%04x" % w for w in words(d["palette"])),
       "static const uint16_t rain_burst_palette[5] = { %s };" % ", ".join("0x%04x" % w for w in words(d["burst_palette"])),
       "static const uint8_t rain_cut_n[96] = { %s };" % ", ".join(str(c[0]) for c in cut),
       "/* rain_cut ready for rain_step, in ROM (a RAM copy cost 1728 bytes of the stack's room): fix_want index offset (col * 32 + row), column, row, tile + 1 */",
       "typedef struct { int16_t off; int8_t dc, dr; uint8_t t1; } RainCut;",
       "static const RainCut rain_cutw[96 * 3] = { %s }; /* [class * 3 + k], 3 slots per class, rain_cut_n[class] used */" % ", ".join(
           "{%d, %d, %d, %d}" % ((e[k] * 32 + e[k + 1], e[k], e[k + 1], e[k + 2] + 1) if k < 3 * n else (0, 0, 0, 0)) for n, e in cut for k in (0, 3, 6))]
for i, s in enumerate(spawn):
    out.append(arr("rain_spawn_%d" % i, sum(([e[0], e[1], e[2], e[3]] for e in s), []), 4) + " /* %s %s: frame, col, row, rows */" % (("far", "near")[i // 3], GU[i % 3]))
out += ["#define RAIN_SPAWN_N { %s }" % ", ".join(str(len(s)) for s in spawn), "#define RAIN_SPAWN_TAB { %s }" % ", ".join("rain_spawn_%d" % i for i in range(6)),
        arr("rain_burst_spawn", sum(([e[0], e[1], e[2], e[3]] for e in d["burst_spawn"]), []), 4) + " /* frame since the flash start, col, row, rows */",
        "#define RAIN_BURST_N %d" % len(d["burst_spawn"]), "", "#endif", ""]
open(a.out, "w").write("\n".join(out))
print("[OK] %s: %d tiles" % (a.out, n))
