#!/usr/bin/env python3
"""Rules card fix tiles: assets/rulecard/rulecard_fix.png (P mode, 128 px wide, 12 tiles, drawn by tools/draw_rulecard_art.py)
-> build/gen/rulecard_tiles.h (palette words, tile ids) + rulecard_tiles.fix (S-ROM order: font, attract icons, result scene, these).
Usage: python3.14 -I tools/build_rulecard_tiles.py --out build/gen/rulecard_tiles.h
Reuses pack_fix from tools/build_attract_icons.py and rgb_to_ng from tools/sprite_pipeline.py."""
import argparse, os, sys
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sprite_pipeline as sp
import build_attract_icons as icons
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TILES = 12

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    png = os.path.join(ROOT, "assets/rulecard/rulecard_fix.png")
    img = Image.open(png)
    assert img.mode == "P" and img.size == (128, 8), (img.mode, img.size)
    p = img.getpalette()
    words = [0x8000] + [sp.rgb_to_ng(tuple(p[i * 3:i * 3 + 3])) for i in range(1, 16)]
    open(a.out, "w").write("\n".join([
        "/* Generated by tools/build_rulecard_tiles.py from assets/rulecard/rulecard_fix.png. Do not edit. */",
        "#ifndef RULECARD_TILES_H", "#define RULECARD_TILES_H", "#include <stdint.h>", '#include "gen/result_scene.h"', "",
        "#define RULECARD_FIX_TILES %d" % TILES,
        "#define RULECARD_FIX_BASE (RESULT_SCENE_BASE + RESULT_SCENE_TILES) /* S-ROM order: font, attract icons, result scene, these */",
        "#define RULECARD_FIX_BUTTON_UP 0   /* 2x2 cells, row-major: button A, cap up */",
        "#define RULECARD_FIX_BUTTON_DOWN 4 /* 2x2 cells: cap pressed */",
        "#define RULECARD_FIX_BAR_EMPTY 8",
        "#define RULECARD_FIX_BAR_POWER 9",
        "#define RULECARD_FIX_BAR_SAFE 10",
        "#define RULECARD_FIX_BAR_FOUL 11",
        '_Static_assert(RULECARD_FIX_BASE + RULECARD_FIX_TILES <= 0x1000, "rules card tiles leave the 12-bit fix code range");',
        "static const uint16_t rulecard_fix_palette[16] = { /* colour 15 = the fill of the strip panel (font plate fill, white font palette) */",
        "    " + ", ".join("0x%04x" % w for w in words), "};", "", "#endif", ""]))
    icons.pack_fix(png, TILES, os.path.splitext(a.out)[0] + ".fix")
    print("[OK] %s: %d tiles" % (a.out, TILES))
