#!/usr/bin/env python3
"""Stadium (ground events) sprite set: every unique 16 x 16 tile of the approved hand-pixeled stand art in
assets/stadium/ (draw_stadium.py + draw_polish.py) -> a one-frame-per-tile sheet + json in --out
-> build/gen/stadium.c1/.c2, stadium_sprites.h/.c, stadium_tables.h (via tools/sprite_pipeline.py).
Usage: $PYTHON -I tools/build_stadium_sprites.py [--out build/gen] [--report]
Tile data is drawn with ONE global char -> palette index map (sorted chars), so a tile is shared by every mood, team and
variant; the look is the palette: extra palette "<mood>_t<team>_v<var>_<near|far>" (S.pal). Owner decisions: the storm far
crowd has no umbrellas (S.FU empty), so storm far cells are the dry far cells with the storm palette.
Frame order: the tile list printed by --report (stand_tiles -> frame k = tile k). The stand tables (which frame sits in
which cell, per mood/mode/frame) are emitted into stadium_cells.h by this script too."""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "assets", "stadium"))
import draw_fling_field as FF
FF.BIRD = os.path.join(os.path.dirname(HERE), "assets", "flier", "sootling_sheet.png")
import draw_stadium as S
import draw_polish as P
from PIL import Image
import sprite_pipeline

S.FU = set()                                   # owner decision: no far umbrellas
BL = P.BLANK


def half(g, k):
    """Left or right 16 px tile of a 32 px wide tower grid."""
    return tuple(r[16 * k:16 * k + 16] for r in g)


TOWER_TILES = [half(g, k) for g in (S.HEAD, S.MAST) for k in (0, 1)]    # head left/right, mast left/right


def grids(mood):
    """Every unique non-blank tile of one mood, by class."""
    near, far = set(), set()
    for mode in S.MODES:
        for f in range(S.NFR[mode]):
            for r in range(3):
                for c in range(21):
                    near |= set(P.near_tiles(mood, mode, f, r, c))
            for r in range(2):
                for c in range(21):
                    far |= set(P.far_tiles(mood, mode, f, r, c))
    S.USED.clear()
    P._STRUCT.pop(mood, None)
    P.struct_plane(mood)
    P.near_plane(mood, "idle", 0)
    struct = set().union(*(v for k, v in S.USED.items() if k[1] in ("struct", "digit")))
    for line in P.scoreboard():
        struct |= {g for g, _, _ in line}
    struct |= set(TOWER_TILES) | {P.digit(n) for n in range(10)}
    light = (set(P.GLOW.values()) | set(P.SH.values())) if mood == "dusk" else set()
    return {"near": near - {BL}, "far": far - {BL}, "struct": struct - {BL} - light, "light": light}


POSE = "ABCDEF"


def fnv(h, v):
    return ((h ^ (v & 0xFFFF)) * 16777619) & 0xFFFFFFFF


def emit_motion(out, tid):
    """build/gen/stadium_motion.h: layout strings, motion tables, the (type, pose, dy) -> tile-pair tables and the far
    sorted-key table, plus the golden checksum of every cell of every mood/mode/frame (src/core/stadium.c must match it)."""
    L = []
    w = L.append
    w("/* GENERATED by tools/build_stadium_sprites.py; do not edit. Tile numbers are relative to STADIUM_TILE_BASE (0 = blank). */")
    w("#ifndef STADIUM_MOTION_H\n#define STADIUM_MOTION_H\n#define ST_U __attribute__((unused))")
    for nm in ("NT", "NV", "NP", "NU", "FB", "FV", "FP"):
        w('static const char ST_%s[%d][22] = {%s};' % (nm, len(getattr(S, nm)), ", ".join('"%s"' % r for r in getattr(S, nm))))
    w("static const ST_U unsigned char ST_BLOCK[5][4] = {%s};   /* far bird phase, 255 = no bird */" % ", ".join(
        "{%s}" % ", ".join("255" if t == "e" else str(ph) for t, _, ph in S.BLOCKS[n]) for n in "ABCDE"))

    def seq(name, d):
        keys = sorted(d) if isinstance(d, dict) else None
        rows = [d[k] for k in keys] if keys else [d]
        n = max(len(r) for r in rows)
        w("static const ST_U signed char ST_%s[%d][%d][2] = {%s};" % (name, len(rows), n, ", ".join("{%s}" % ", ".join(
            "{%d, %d}" % (POSE.index(p), dy) for p, dy in r) for r in rows)))
        w("static const ST_U unsigned char ST_%s_LEN[%d] = {%s};" % (name, len(rows), ", ".join(str(len(r)) for r in rows)))
    for nm in ("IDLE", "CHEER", "WAVE"):
        seq(nm, getattr(S, nm))
    for nm in ("SLUMP", "IDLE_F", "CHEER_F", "WAVE_F"):
        seq(nm, getattr(S, nm))
    w("static const ST_U unsigned char ST_CHEER_AT[2] = {%d, %d};" % S.CHEER_AT)
    DY0 = 10
    used = set()
    for mode in S.MODES:
        for f in range(S.NFR[mode]):
            for r in range(3):
                for c in range(21):
                    if S.NT[r][c] not in "se":
                        pose, dy = S.near_state(mode, f, r, c)
                        used.add((S.NT[r][c], pose, dy))
    tab = [[[[0xFFFF, 0xFFFF] for _ in range(12)] for _ in range(6)] for _ in range(3)]
    for t, pose, dy in used:
        assert -DY0 <= dy < 2
        tp, bt = P.cell2(P.BIRD[t][pose], dy)
        tab["abc".index(t)][POSE.index(pose)][dy + DY0] = [tid(tp), tid(bt)]
    w("static const ST_U unsigned short ST_NEAR[3][6][12][2] = {%s};   /* [type][pose][dy + 10] = {head-room tile, seat tile} */" % ", ".join(
        "{%s}" % ", ".join("{%s}" % ", ".join("{%d, %d}" % tuple(e) for e in row) for row in t) for t in tab))
    umb = []
    for dy in range(-DY0, 2):
        try:
            tp, bt = P.cell2(S.UMB, dy)
            umb.append((tid(tp), tid(bt)))
        except (AssertionError, KeyError):
            umb.append((0xFFFF, 0xFFFF))
    w("static const ST_U unsigned short ST_UMB[12][2] = {%s};" % ", ".join("{%d, %d}" % e for e in umb))
    et, eb = P.cell2(S.EMPTY, 0)
    w("static const ST_U unsigned short ST_EMPTY[2] = {%d, %d}, ST_AISLE[2] = {%d, %d};" % (tid(et), tid(eb), tid(P.BLANK), tid(S.AISLE)))
    w("static const ST_U unsigned short ST_DIGIT[10] = {%s};" % ", ".join(str(tid(P.digit(n))) for n in range(10)))

    def fkey(mode, f, row, bc):
        name = S.FB[row][bc]
        k = "ABCDE".index(name)
        for i, (t, _, ph) in enumerate(S.BLOCKS[name]):
            if t != "e":
                pose, dy = S.far_state(mode, f, row, bc, ph)
                assert -8 <= dy < 8
                k |= ((POSE.index(pose) + 1) | ((dy + 8) << 3)) << (3 + 7 * i)
        return k
    far = {}
    for mode in S.MODES:
        for f in range(S.NFR[mode]):
            for row in range(2):
                for bc in range(21):
                    if S.FB[row][bc] != "S":
                        tp, bt = P.far_tiles("dusk", mode, f, row, bc)
                        far[fkey(mode, f, row, bc)] = (tid(tp), tid(bt))
    ks = sorted(far)
    w("#define ST_FAR_N %d" % len(ks))
    w("static const ST_U unsigned long ST_FAR_KEY[ST_FAR_N] = {%s};" % ", ".join("%dUL" % k for k in ks))
    w("static const ST_U unsigned short ST_FAR_TILE[ST_FAR_N][2] = {%s};" % ", ".join("{%d, %d}" % far[k] for k in ks))
    h = 2166136261
    for mood in S.MOODS:
        for mode in S.MODES:
            for f in range(S.NFR[mode]):
                for r in range(3):
                    for c in range(21):
                        for g in P.near_tiles(mood, mode, f, r, c):
                            h = fnv(h, tid(g))
                for row in range(2):
                    for c in range(21):
                        for g in P.far_tiles(mood, mode, f, row, c):
                            h = fnv(h, tid(g))
    w("#define ST_GOLDEN 0x%08XUL" % h)
    w("#endif")
    open(os.path.join(out, "stadium_motion.h"), "w").write("\n".join(L) + "\n")
    print("[INFO] motion: %d far keys, golden %08X" % (len(ks), h), file=sys.stderr)


GAME_MOODS = ("moon", "dusk", "storm")   # src/core/game.h GAME_MOOD_* order
GROUP_ROWS = 8                           # both merged sprite groups are 8 tiles tall


def emit_layout(out, tid, pals):
    """build/gen/stadium_layout.h: the two merged sprite groups of src/stadium_hw.c. Group 0 = upper structure (rows 0..2: scoreboard,
    roof), far row 1 (rows 3..4), balcony fascia (row 5), near row 1 (rows 6..7). Group 1 = far row 0 (rows 2..3), near row 0 (rows 5..6),
    near row 2 (rows 7..8), boards (row 9); it sits above group 0. ST_LT = tile (0 = blank, also every crowd cell: the game fills those),
    ST_LP = extra palette index | flip << 7. The two floodlight towers (plane x 40 and 264, not on the 16 px stand grid) are their own sprites."""
    idx = {n: i for i, n in enumerate(pals)}

    def tf(g):
        """(tile, mirrored): the sheet keeps one of a tile and its mirror image."""
        try:
            return tid(g), False
        except KeyError:
            return tid(tuple(r[::-1] for r in g)), True
    rim = lambda mood, g, c: S.over(g, P.RIM[P.RIMROW[c]]) if mood == "dusk" else g
    sn = lambda mood, team, far: idx["%s_t%d_struct_%s" % (mood, team, "far" if far else "near")]
    lt = [[[[0] * GROUP_ROWS for _ in range(21)] for _ in range(2)] for _ in GAME_MOODS]
    lp = [[[[0] * GROUP_ROWS for _ in range(21)] for _ in range(2)] for _ in GAME_MOODS]
    top, bot = P.scoreboard()
    for m, mood in enumerate(GAME_MOODS):
        for c in range(21):
            team = 0 if c < 10 else 1

            def put(grp, row, g, pal, flip=False):
                t, mir = tf(g) if g is not None else (0, False)
                lt[m][grp][c][row] = t
                lp[m][grp][c][row] = pal | (128 if flip != mir else 0)
            put(0, 2, rim(mood, S.ROOF_LAMP if S.ROOFROW[c] == "L" else S.ROOF, c), sn(mood, team, True))
            put(0, 5, rim(mood, S.over(S.FASCIA, S.BANNER) if S.FASROW[c] == "B" else S.FASCIA, c), sn(mood, team, True))
            put(1, 7, rim(mood, S.board(S.BOARDROW[c], team), c), sn(mood, team, False))
            for grp, row, r, far in ((0, 3, 1, True), (0, 4, 1, True), (0, 6, 1, False), (0, 7, 1, False),
                                     (1, 0, 0, True), (1, 1, 0, True), (1, 3, 0, False), (1, 4, 0, False), (1, 5, 2, False), (1, 6, 2, False)):
                var = int(S.FV[r][c] if far else S.NV[r][c])
                put(grp, row, None, idx["%s_t%d_v%d_%s" % (mood, team, var, "far" if far else "near")])
        for row, line in enumerate((top, bot)):
            for i, (g, team, flip) in enumerate(line):
                t, mir = tf(g)
                lt[m][0][7 + i][row] = t
                lp[m][0][7 + i][row] = sn(mood, team, False) | (128 if flip != mir else 0)
    L = ["/* GENERATED by tools/build_stadium_sprites.py; do not edit. Tile numbers are relative to STADIUM_TILE_BASE (0 = blank). */",
         "#ifndef STADIUM_LAYOUT_H\n#define STADIUM_LAYOUT_H"]
    arr = lambda name, ty, a: L.append("static const %s %s[3][2][21][%d] = %s;" % (ty, name, GROUP_ROWS, repr(a).replace("[", "{").replace("]", "}")))
    arr("ST_LT", "unsigned short", lt)
    arr("ST_LP", "unsigned char", lp)
    first = [min(i for n, i in idx.items() if n.startswith(m + "_")) for m in GAME_MOODS]
    count = [sum(1 for n in idx if n.startswith(m + "_")) for m in GAME_MOODS]
    for m, f, k in zip(GAME_MOODS, first, count):
        assert [idx[n] for n in pals if n.startswith(m + "_")] == list(range(f, f + k)), "extra palettes of a mood are not contiguous"
    L.append("static const unsigned char ST_PAL_FIRST[3] = {%s}, ST_PAL_COUNT[3] = {%s};   /* extra palettes of each game mood */" % (
        ", ".join(map(str, first)), ", ".join(map(str, count))))
    L.append("static const unsigned short ST_TOWER_X[2] = {%d, %d}, ST_TOWER_TILE[4] = {%d, %d, %d, %d};   /* plane x of the two towers; tiles: head left, head right, mast left, mast right */" % (
        S.TOWERS[0], S.TOWERS[1], *(tid(g) for g in TOWER_TILES)))
    L.append("static const unsigned char ST_TOWER_PAL[3] = {%s};" % ", ".join(str(sn(m, 0, True)) for m in GAME_MOODS))
    L.append("static const unsigned char ST_DIGIT_COL[4] = {8, 9, 11, 12};   /* scoreboard digit cells, group 0 row 1 */")
    L.append("#endif")
    open(os.path.join(out, "stadium_layout.h"), "w").write("\n".join(L) + "\n")


def main():
    out = "build/gen"
    for i, a in enumerate(sys.argv):
        if a == "--out" and i + 1 < len(sys.argv):
            out = sys.argv[i + 1]
    per = {m: grids(m) for m in S.MOODS}
    # two char -> index maps (a palette is chosen per cell anyway): crowd tiles (near + far birds) and structure tiles
    crowd = sorted(set().union(*(m[k] for m in per.values() for k in ("near", "far"))))
    struct = sorted(set().union(*(m["struct"] for m in per.values())) - set(crowd))
    light = sorted(set().union(*(m["light"] for m in per.values())) - set(crowd) - set(struct))
    cch = sorted({c for g in crowd for r in g for c in r} - {"."})
    sch = sorted({c for g in struct for r in g for c in r} - {"."})
    lch = sorted({c for g in light for r in g for c in r} - {"."})
    for nm, cs in (("crowd", cch), ("struct", sch), ("light", lch)):
        if len(cs) > 15:
            raise SystemExit("[ERROR] %s tile art uses %d chars, hardware limit 15: %s" % (nm, len(cs), "".join(cs)))
    maps = {"crowd": {c: i + 1 for i, c in enumerate(cch)}, "struct": {c: i + 1 for i, c in enumerate(sch)},
            "light": {c: i + 1 for i, c in enumerate(lch)}}
    refc = [FF.snap((8 * (i + 1) % 256, 255 - 8 * i, 8 * (i * 7 % 31))) for i in range(15)]
    assert len(set(refc)) == 15
    allt = [(g, "crowd") for g in crowd] + [(g, "struct") for g in struct] + [(g, "light") for g in light]
    sheet = Image.new("RGBA", (16 * len(allt), 16), (0, 0, 0, 0))
    for k, (g, cl) in enumerate(allt):
        for j, row in enumerate(g):
            for i, ch in enumerate(row):
                if ch != ".":
                    sheet.putpixel((16 * k + i, j), refc[maps[cl][ch] - 1] + (255,))
    pal0 = [list(c) for c in refc]
    extra = {}
    for mood in S.MOODS:
        for team in (0, 1):
            for var in (0, 1, 2):
                for far in (False, True):
                    p = S.pal(mood, team, var, far)[0]
                    extra["%s_t%d_v%d_%s" % (mood, team, var, "far" if far else "near")] = [list(p[c]) for c in cch] + [[0, 0, 0]] * (15 - len(cch))
            for far in (False, True):
                p = S.pal(mood, team, 0, far)[0]
                extra["%s_t%d_struct_%s" % (mood, team, "far" if far else "near")] = [list(p[c]) for c in sch] + [[0, 0, 0]] * (15 - len(sch))
        if mood == "dusk":      # sun, glow and the long turf shadow; '#' is the shadow mesh, drawn in the dark outline colour
            p = S.pal(mood, 0, 0, False)[0]
            extra["dusk_light"] = [list(p.get(c, p["K"])) for c in lch] + [[0, 0, 0]] * (15 - len(lch))
    anims = {"stand": [dict(x=16 * k, y=0, w=16, h=16) for k in range(len(allt))]}
    meta = dict(animations=anims, palettes=dict(stand=pal0), extra_palettes=extra,
                defines=dict(stand_tiles=len(allt), crowd_tiles=len(crowd)))
    os.makedirs(out, exist_ok=True)
    sp, mp = os.path.join(out, "stadium_sheet.png"), os.path.join(out, "stadium_sheet.json")
    sheet.save(sp)
    json.dump(meta, open(mp, "w"))
    cls = lambda m, k: per[m][k]
    for m in S.MOODS:
        print("[INFO] %-5s struct %3d near %3d far %3d  total(unique) %3d" % (m, len(cls(m, "struct")), len(cls(m, "near")),
              len(cls(m, "far")), len(set().union(*per[m].values()))), file=sys.stderr)
    print("[INFO] all moods: %d crowd + %d struct = %d unique tiles; crowd chars %s struct chars %s" % (len(crowd), len(struct), len(allt), "".join(cch), "".join(sch)), file=sys.stderr)
    if "--report" in sys.argv:
        return
    gidx = {g: i + 1 for i, (g, _) in enumerate(allt)}
    gidx[BL] = 0
    emit_motion(out, lambda g: gidx[g])
    emit_layout(out, lambda g: gidx[g], list(extra))
    sys.argv = [a for a in sys.argv if a not in ("--out", out, "--report")] + ["--out", out]
    sprite_pipeline.main("stadium", sp, mp)


if __name__ == "__main__":
    main()
